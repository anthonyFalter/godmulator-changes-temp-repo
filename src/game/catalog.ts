export function getDragonVariant(appearanceSeed?: number): DragonVariantPalette {
  const seed = Math.abs(Math.floor(appearanceSeed ?? 1) || 1);
  const s0 = Math.abs(Math.imul(seed ^ 0x9e3779b9, 2654435761)) >>> 0;
  return DRAGON_VARIANTS[s0 % DRAGON_VARIANTS.length];
}

export interface DinosaurVariantInfo {
  morph: 0 | 1 | 2;
  speciesName: 'Tyrannosaur' | 'Triceratops' | 'Stegosaurus';
  diet: 'carnivore' | 'herbivore';
}

export function getDinosaurVariant(appearanceSeed?: number): DinosaurVariantInfo {
  const seed = Math.abs(Math.floor(appearanceSeed ?? 1) || 1);
  const s0 = Math.abs(Math.imul(seed ^ 0x9e3779b9, 2654435761)) >>> 0;
  const morph = (s0 % 3) as 0 | 1 | 2;
  if (morph === 0) {
    return { morph: 0, speciesName: 'Tyrannosaur', diet: 'carnivore' };
  }
  if (morph === 1) {
    return { morph: 1, speciesName: 'Triceratops', diet: 'herbivore' };
  }
  return { morph: 2, speciesName: 'Stegosaurus', diet: 'herbivore' };
}

export function getUnitMaxLifespan(unit: {
  role: UnitRole;
  species: SpeciesId;
  appearanceSeed?: number;
  genes?: string[];
  maxLifespan?: number;
}): number {
  if (typeof unit.maxLifespan === 'number' && Number.isFinite(unit.maxLifespan) && unit.maxLifespan > 0) {
    return Math.round(unit.maxLifespan);
  }
  const seed = Math.abs(Math.floor(unit.appearanceSeed ?? 1));
  let base: number;
  switch (unit.role) {
    case 'dragon':
    case 'leviathan':
    case 'phoenix':
    case 'golem':
    case 'hydra':
    case 'ent':
    case 'kraken':
    case 'gargoyle':
      base = 500 + (seed % 65);
      break;
    case 'unicorn':
    case 'kitsune':
    case 'pegasus':
    case 'thunderbird':
    case 'fairy':
    case 'fae':
    case 'will_o_wisp':
      base = 350 + (seed % 70);
      break;
    case 'griffin':
    case 'yeti':
    case 'minotaur':
    case 'cerberus':
    case 'basilisk':
    case 'manticore':
      base = 240 + (seed % 55);
      break;
    case 'turtle':
      base = 85 + (seed % 25);
      break;
    case 'dinosaur':
    case 'elephant':
      base = 65 + (seed % 26);
      break;
    case 'crocodile':
    case 'hippo':
    case 'rhino':
    case 'gorilla':
    case 'ostrich':
      base = 46 + (seed % 16);
      break;
    case 'camel':
    case 'horse':
    case 'giraffe':
    case 'zebra':
    case 'flamingo':
    case 'seal':
      base = 32 + (seed % 10);
      break;
    case 'bear':
    case 'polar_bear':
    case 'panda':
    case 'bison':
    case 'moose':
    case 'giant_spider':
      base = 26 + (seed % 8);
      break;
    case 'cow':
    case 'lion':
    case 'tiger':
    case 'penguin':
    case 'monkey':
    case 'kangaroo':
      base = 18 + (seed % 7);
      break;
    case 'wolf':
    case 'deer':
    case 'boar':
    case 'goat':
      base = 16 + (seed % 7);
      break;
    case 'pig':
    case 'sheep':
      base = 15 + (seed % 6);
      break;
    case 'capybara':
    case 'fox':
      base = 12 + (seed % 5);
      break;
    case 'chicken':
    case 'rabbit':
    case 'frog':
    case 'crab':
    case 'firefly':
    case 'glow_moth':
    case 'lantern_jelly':
      base = 8 + (seed % 5);
      break;
    case 'raider_swarmer':
    case 'raider_ranged':
    case 'raider_behemoth':
      base = 50 + (seed % 16);
      break;
    case 'skeleton':
      base = 120 + (seed % 30);
      break;
    case 'alien_trooper':
    case 'alien_ufo':
    case 'alien_walker':
      base = 240 + (seed % 40);
      break;
    default:
      if (unit.species === 'elf') {
        base = 215 + (seed % 50);
      } else if (unit.species === 'orc') {
        base = 68 + (seed % 16);
      } else if (unit.species === 'dwarf') {
        base = 145 + (seed % 35);
      } else if (unit.species === 'lizardfolk') {
        base = 115 + (seed % 30);
      } else {
        base = 88 + (seed % 20);
      }
      break;
  }

  let geneBonus = 0;
  if (unit.genes) {
    for (const g of unit.genes) {
      if (g === 'Tough' || g === 'Hardy Constitution') {
        geneBonus += unit.role === 'chicken' ? 3 : unit.role === 'capybara' ? 4 : 12;
      } else if (g === 'Dragon Blood' || g === 'Ancient Wyrmblood') geneBonus += 60;
      else if (g === 'Large Frame' || g === 'Alpha Stature') geneBonus += 5;
      else if (g === 'Forest Bond' || g === 'Starleaf Resonance') geneBonus += 18;
    }
  }

  return base + geneBonus;
}


